export function getStudioLightingPreset(id: StudioLightingPresetId): StudioLightingPreset {
	const found = STUDIO_LIGHTING_PRESETS.find((preset) => preset.id === id);
	return found ?? STUDIO_LIGHTING_PRESETS[0];
}

export function applyStudioLightingPreset(
	current: StudioLightingSettings,
	presetId: StudioLightingPresetId,
): StudioLightingSettings {
	if (presetId === "custom") {
		return {
			...current,
			presetId: "custom",
		};
	}
	const preset = getStudioLightingPreset(presetId);
	return {
		...current,
		presetId,
		...preset.settings,
		lights: preset.settings.lights.map((l) => ({ ...l })),
	};
}
