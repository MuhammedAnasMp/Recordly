const CUSTOM_PRESETS_STORAGE_KEY = "recordly_custom_caption_presets";

export function getCustomCaptionPresets(): CaptionPreset[] {
	try {
		if (typeof window === "undefined") return [];
		const stored = localStorage.getItem(CUSTOM_PRESETS_STORAGE_KEY);
		return stored ? JSON.parse(stored) : [];
	} catch (e) {
		console.error("Failed to load custom caption presets:", e);
		return [];
	}
}

export function saveCustomCaptionPreset(preset: CaptionPreset): CaptionPreset[] {
	const current = getCustomCaptionPresets();
	const existingIndex = current.findIndex((p) => p.id === preset.id);
	const updated = [...current];
	const prepared = { ...preset, isCustom: true };

	if (existingIndex >= 0) {
		updated[existingIndex] = prepared;
	} else {
		updated.push(prepared);
	}

	try {
		localStorage.setItem(CUSTOM_PRESETS_STORAGE_KEY, JSON.stringify(updated));
	} catch (e) {
		console.error("Failed to save custom caption preset:", e);
	}

	return updated;
}

export function deleteCustomCaptionPreset(presetId: string): CaptionPreset[] {
	const current = getCustomCaptionPresets();
	const updated = current.filter((p) => p.id !== presetId);
	try {
		localStorage.setItem(CUSTOM_PRESETS_STORAGE_KEY, JSON.stringify(updated));
	} catch (e) {
		console.error("Failed to delete custom caption preset:", e);
	}
	return updated;
}
